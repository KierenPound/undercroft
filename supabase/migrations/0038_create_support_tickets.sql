-- ============================================================================
-- Support tickets
--
-- Moved from the retired CrabKing's Lair project. Inserts arrive from the
-- Cloudflare Worker at worker.crabkingslair.com/api/support (used by the
-- UnderCroft app support form and the CrabKing's Lair support page).
-- Reads are done server-side with the secret key, so there is no anon SELECT
-- policy here.
-- ============================================================================

create table if not exists public.support_tickets (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default timezone('utc'::text, now()),

  -- Submitter
  user_email    text,
  user_name     text,
  user_id       uuid default gen_random_uuid(),

  -- Ticket details
  subject       text,
  message       text,
  screenshot    text,                 -- base64 data URL, embedded inline in the notification email
  platform      text default 'ios'::text,
  app_version   text,

  -- Internal management
  status        text not null default 'open'::text,
  notes         text
);

alter table public.support_tickets enable row level security;

-- Table-level privileges for the roles that insert into this table. The
-- Cloudflare Worker uses service_role; the app/pubnlic form uses anon.
grant insert on public.support_tickets to service_role, anon, authenticated;

drop policy if exists "Anyone can submit a support ticket" on public.support_tickets;
create policy "Anyone can submit a support ticket"
  on public.support_tickets for insert to anon, authenticated with check (true);

-- Keeps the identity sequence correct. Re-run this after copying rows in from
-- the retired CrabKing's Lair project if you import them after this migration,
-- otherwise inserts collide with the imported ids.
select setval(
  pg_get_serial_sequence('public.support_tickets', 'id'),
  coalesce((select max(id) from public.support_tickets), 1),
  (select max(id) is not null from public.support_tickets)
);

